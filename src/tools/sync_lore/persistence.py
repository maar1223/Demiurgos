"""
persistence.py — Write lore index to disk and optionally to Engram.

Outputs lore-index.json and a human-readable report to stdout.
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
from dataclasses import asdict
from pathlib import Path
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from .schemas import LoreIndex


# ---------------------------------------------------------------------------
# JSON persistence
# ---------------------------------------------------------------------------

def _serialize_index(index: "LoreIndex") -> dict:
    """Convert LoreIndex to a JSON-serializable dict."""
    result: dict = {
        "meta": asdict(index.meta),
        "entities": [],
        "terms": index.terms,
        "images": index.images,  # already serializable
        "contradictions": [],
    }

    for e in index.entities:
        result["entities"].append({
            "id": e.id,
            "name": e.name,
            "type": e.type,
            "world": e.world,
            "source_file": e.source_file,
            "chunk_ref": e.chunk_ref,
            "description": e.description,
            "relations": e.relations,
            "terms": e.terms,
            "stal_tier": e.stal_tier,
            "immutable": e.immutable,
            "quotes": e.quotes,
            "contradictions": e.contradictions,
        })

    for c in index.contradictions:
        result["contradictions"].append({
            "id": c.id,
            "entity": c.entity,
            "entity_id": c.entity_id,
            "chunk_a": c.chunk_a,
            "chunk_b": c.chunk_b,
            "reason": c.reason,
            "stal_conflict": c.stal_conflict,
        })

    return result


def write_lore_index(index: "LoreIndex", output_dir: Path) -> Path:
    """
    Write lore-index.json to the output directory.

    Args:
        index: Complete LoreIndex to persist.
        output_dir: Directory to write the JSON file.

    Returns:
        Path to the written file.
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    output_path = output_dir / "lore-index.json"

    data = _serialize_index(index)
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    return output_path


# ---------------------------------------------------------------------------
# Engram persistence (best-effort via subprocess CLI)
# ---------------------------------------------------------------------------

def try_engram_save(index: "LoreIndex", world: str | None) -> bool:
    """
    Attempt to persist the lore index to Engram via the CLI.

    Best-effort: does NOT block or fail if Engram is unavailable.
    Uses subprocess call to `engram mem save`.

    Args:
        index: Complete LoreIndex.
        world: World name (used as --project).

    Returns:
        True if Engram save succeeded, False otherwise.
    """
    world_name = world or "generic"

    content = (
        f"**What**: Lore index generated by sync-lore\\n"
        f"**Why**: Automated lore ingestion pipeline\\n"
        f"**Where**: output/lore-index.json\\n"
        f"**Stats**: {index.meta.entities_extracted} entities, "
        f"{len(index.terms)} terms, "
        f"{len(index.contradictions)} contradictions"
    )

    try:
        result = subprocess.run(
            [
                "engram", "mem", "save",
                "--project", world_name,
                "--topic-key", f"lore/{world_name}/index",
                "--title", f"Lore Index — {world_name}",
                "--type", "discovery",
                "--content", content,
                "--capture-prompt", "false",
            ],
            capture_output=True,
            text=True,
            timeout=15,
        )
        return result.returncode == 0
    except (FileNotFoundError, subprocess.TimeoutExpired, OSError):
        return False


# ---------------------------------------------------------------------------
# Report
# ---------------------------------------------------------------------------

def print_report(
    index: "LoreIndex",
    output_path: Path,
    engram_ok: bool,
    files_processed: int = 0,
    files_omitted: int = 0,
    chunks_failed: int = 0,
    images_processed: int = 0,
) -> None:
    """
    Print a human-readable report to stdout (stderr for logs, stdout for data).

    Args:
        index: Complete LoreIndex.
        output_path: Path where lore-index.json was written.
        engram_ok: Whether Engram save succeeded.
        files_processed: Number of files processed.
        files_omitted: Number of files omitted.
        chunks_failed: Number of chunks that failed.
        images_processed: Number of images processed.
    """
    world_str = index.meta.world or "generic"
    mode_str = index.meta.mode

    lines = [
        "",
        "=" * 50,
        "=== sync-lore Report ===",
        f"Mundo: {world_str}",
        f"Modo: {mode_str}",
        f"Archivos: {files_processed} procesados, {files_omitted} omitidos",
        f"Chunks: {index.meta.chunks_processed} procesados, {chunks_failed} fallidos",
        f"Entidades extra\u00eddas: {index.meta.entities_extracted}",
        f"T\u00e9rminos: {len(index.terms)}",
        f"Im\u00e1genes: {images_processed}",
        f"Contradicciones: {index.meta.contradictions_found}",
    ]

    # Contradictions section
    if index.contradictions:
        lines.append("=== Contradicciones Detectadas ===")
        for c in index.contradictions:
            prefix = "\u274c"  # ❌
            if c.stal_conflict:
                prefix = "\u26a0\ufe0f [Staler T1]"
            lines.append(
                f"{prefix} {c.entity}: "
                f"{c.chunk_a.get('heading', '?')} vs "
                f"{c.chunk_b.get('heading', '?')}"
            )
            if c.reason:
                lines.append(f"   \u2192 {c.reason}")

    # Output section
    lines.append("=== Output ===")
    lines.append(f"lore-index.json \u2192 {output_path}")
    if engram_ok:
        lines.append(f"Engram: {index.meta.entities_extracted} entidades persistidas")
    else:
        lines.append("Engram: no disponible (solo archivo local)")

    lines.append("=" * 50)

    print("\n".join(lines), file=sys.stderr)
