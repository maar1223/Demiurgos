import ReactMarkdown from "react-markdown";
import remarkGfm from "remark-gfm";
import type { Components } from "react-markdown";
import { useState } from "react";
import { cn } from "@/lib/utils";
import { remarkWikiLink } from "@/lib/remarkWikiLink";
import { WikiLink } from "@/components/atoms/WikiLink";
import { Spinner } from "@/components/atoms/Spinner";
import { ErrorBanner } from "@/components/organisms/ErrorBanner";
import { EmptyState } from "@/components/organisms/EmptyState";
import { getMediaUrl } from "@/api/wiki";
import { Icon } from "@/components/atoms/Icon";
import { splitFrontmatter } from "@/lib/frontmatter";
import { useAppLanguage } from "@/hooks/useAppLanguage";

export type ImageFit = "contain" | "cover";

interface MarkdownViewerProps {
  content?: string | null;
  fileName?: string;
  isLoading?: boolean;
  error?: Error | null;
  onRetry?: () => void;
  /** Current world name — required for wikilink entity URL construction */
  mundo?: string;
  /**
   * Image fit when rendering without a world (e.g. the global idea bank).
   * "contain" keeps exact proportions and shows the full image (no crop);
   * "cover" fills the box (crops), used by the mundo gallery. When unset,
   * images only render via MarkdownImage when `mundo` is present (legacy).
   */
  imageFit?: ImageFit;
}

/**
 * Renders GFM markdown content via react-markdown + remark-gfm.
 *
 * Uses @tailwindcss/typography (`prose`) with the theme-aware
 * `.prose-demiurgos` class, which maps prose colors to the brand role
 * tokens (flipping light/dark via :root / :root.dark).
 *
 * Supports [[Name]] wikilinks via a custom `remarkWikiLink` plugin.
 * Wikilinks are resolved lazily against the entity search API and rendered
 * as clickable `<WikiLink>` components with alive/dead states.
 *
 * When `mundo` is provided, relative image paths are rewritten to
 * `/api/{mundo}/media?path=` so wiki images render correctly. Size and
 * alignment suffixes (`#left-sm`, `#right-lg`, `#center`, `#sm`, …) are
 * parsed from the image source and applied as CSS classes.
 *
 * States:
 * - 🟡 Loading: Spinner centered in content area
 * - 🟢 No file selected: "Seleccioná un archivo" placeholder
 * - 🔴 Error: ErrorBanner with retry
 * - 🟢 Empty content: file selected but no content
 * - 🟢 Content: rendered markdown with wikilinks
 */
export function MarkdownViewer({
  content,
  fileName,
  isLoading = false,
  error = null,
  onRetry,
  mundo,
  imageFit,
}: MarkdownViewerProps) {
  const { t } = useAppLanguage();
  // Hide the YAML frontmatter block — only the body is rendered. Defense
  // in depth: the wiki editor already strips it before display, but this
  // viewer is also used by the entity page, so it must never leak the
  // agent-only metadata regardless of the caller.
  const { body } = splitFrontmatter(content ?? "");

  // Loading state
  if (isLoading) {
    return (
      <div className="flex items-center justify-center py-24">
        <Spinner size="lg" />
      </div>
    );
  }

  // Error state
  if (error) {
    return (
      <div className="px-4 py-8">
        <ErrorBanner
          message={error.message || t("markdown.loadError")}
          onRetry={onRetry}
        />
      </div>
    );
  }

  // No file selected state
  if (content === undefined || content === null) {
    return (
      <EmptyState
        icon="file"
        message={t("markdown.noFile")}
      />
    );
  }

  // Empty file content
  if (content === "") {
    return (
      <EmptyState
        icon="file"
        message={t("markdown.emptyFile", {
          name: fileName ?? t("markdown.unnamed"),
        })}
      />
    );
  }

  // Render markdown — the img component is only wired up when `mundo` is
  // known so relative paths can be rewritten against the media API. When an
  // `imageFit` is supplied (no-mundo surfaces like the global idea bank) the
  // img component is also wired so images get a consistent, proportion-
  // preserving size instead of rendering at full resolution.
  return (
    <MarkdownBody content={body} mundo={mundo} imageFit={imageFit} />
  );
}

/**
 * Render-only markdown body shared by the wiki viewer and the assistant
 * chat: full prose hierarchy (no flattened overrides), [[wikilinks]] via
 * remarkWikiLink, and wiki-aware image handling.
 */
export function MarkdownBody({
  content,
  mundo,
  className,
  imageFit,
}: {
  content: string;
  mundo?: string;
  className?: string;
  imageFit?: ImageFit;
}) {
  const components: Components = {
    a({ href, children, ...props }) {
      // Intercept wiki:// URLs generated by remarkWikiLink plugin
      if (href?.startsWith("wiki://")) {
        const name = href.slice("wiki://".length);
        return (
          <WikiLink name={name} mundo={mundo ?? ""} />
        );
      }
      // Standard external/internal link — render as normal anchor
      return (
        <a href={href} {...props}>
          {children}
        </a>
      );
    },
    ...(mundo || imageFit
      ? {
          img: ({ src, alt }: { src?: string; alt?: string }) => (
            <MarkdownImage src={src} alt={alt} mundo={mundo ?? ""} imageFit={imageFit} />
          ),
        }
      : {}),
  };

  return (
    <div className={cn("prose prose-demiurgos max-w-none", className)}>
      <ReactMarkdown
        remarkPlugins={[remarkGfm, remarkWikiLink]}
        components={components}
      >
        {content}
      </ReactMarkdown>
    </div>
  );
}

interface MarkdownImageProps {
  src?: string;
  alt?: string;
  mundo?: string;
  imageFit?: ImageFit;
}

/**
 * Custom img component that rewrites relative image paths to use the
 * wiki media API endpoint. Shows a broken-image placeholder on error.
 * `imageFit` = "contain" preserves exact proportions and shows the full
 * image (no crop) — used by no-world surfaces like the global idea bank.
 */
function MarkdownImage({ src, alt, mundo = "", imageFit }: MarkdownImageProps) {
  const { t } = useAppLanguage();
  const [hasError, setHasError] = useState(false);
  // Bump to force a fresh <img> load after a transient error — the browser can
  // abort a deferred/lazy request mid-flight even though the server served the
  // image, and without a reset a single onError permanently showed "imagen no
  // disponible" (sticky state that scrolling could never clear).
  const [attempt, setAttempt] = useState(0);

  // Extract alignment and size suffix (#left, #left-sm, #right-lg, #sm, etc.)
  const suffixMatch = src?.match(/#(left|right|center|sm|lg)(?:-(sm|lg))?$/i);
  let align: "left" | "right" | "center" | undefined;
  let size: "sm" | "md" | "lg" = "md";

  if (suffixMatch) {
    const tag = suffixMatch[1].toLowerCase();
    if (tag === "sm" || tag === "lg") {
      size = tag;
      // Size-only suffix → centered block
    } else {
      align = tag as "left" | "right" | "center";
      if (suffixMatch[2]) {
        size = suffixMatch[2].toLowerCase() as "sm" | "lg";
      }
    }
  }

  const hasSuffix = !!suffixMatch;
  const cleanSrc = hasSuffix
    ? src?.replace(/#(left|right|center|sm|lg)(?:-(sm|lg))?$/i, "")
    : src;

  // Only rewrite relative paths (not external URLs or API paths).
  // Data URIs and absolute URLs pass through as-is.
  const resolvedSrc =
    cleanSrc &&
    mundo &&
    !cleanSrc.startsWith("http://") &&
    !cleanSrc.startsWith("https://") &&
    !cleanSrc.startsWith("/api/") &&
    !cleanSrc.startsWith("data:")
      ? getMediaUrl(mundo, cleanSrc)
      : cleanSrc;

  // CSS classes for each alignment option
  const alignStyles: Record<string, string> = {
    left: "float-left mr-10 mb-6",
    right: "float-right ml-10 mb-6",
    center: "block mx-auto my-4",
  };

  // CSS classes for each size option
  const sizeStyles: Record<string, string> = {
    sm: "max-w-[150px] max-h-[150px]",
    md: "max-w-[300px] max-h-[300px]",
    lg: "max-w-[500px] max-h-[500px]",
  };

  // object-contain: keep exact proportions and show the full image (no crop).
  // object-cover: fill the box (crop), the mundo gallery default.
  const fitClass = imageFit === "contain" ? "object-contain" : "object-cover";

  const imgClassName =
    `rounded-lg h-auto ${fitClass} ${sizeStyles[size]} ${
      align ? alignStyles[align] : hasSuffix ? "block mx-auto my-4" : ""
    }`.trim();

  if (hasError || !resolvedSrc) {
    return (
      <span className="inline-flex items-center gap-2 rounded-lg border border-edge bg-surface-raised px-4 py-3 text-small text-muted">
        <Icon name="image" size={16} />
        {alt
          ? t("markdown.imageUnavailableAlt", { alt })
          : t("markdown.imageUnavailable")}
        {resolvedSrc && (
          <button
            type="button"
            className="text-action underline-offset-2 hover:underline"
            onClick={() => {
              setHasError(false);
              setAttempt((a) => a + 1);
            }}
          >
            Reintentar
          </button>
        )}
      </span>
    );
  }

  return (
    <img
      key={attempt}
      src={resolvedSrc}
      alt={alt ?? ""}
      onError={() => setHasError(true)}
      onLoad={() => setHasError(false)}
      className={imgClassName}
    />
  );
}
